import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { InstanceConfig } from "./types.ts";

export function parseProperties(text: string) {
  const map = new Map<string, string>();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    map.set(line.slice(0, eq), line.slice(eq + 1));
  }
  return map;
}

export function stringifyProperties(map: Map<string, string>) {
  const lines = ["# Generated by tekkit-host"];
  for (const [key, value] of map) lines.push(`${key}=${value}`);
  return `${lines.join("\n")}\n`;
}

export function writeEula(dir: string) {
  writeFileSync(join(dir, "eula.txt"), "eula=true\n");
}

export function applyServerProperties(dir: string, instance: InstanceConfig) {
  const file = join(dir, "server.properties");
  const map = existsSync(file)
    ? parseProperties(readFileSync(file, "utf8"))
    : new Map<string, string>();

  const values: Record<string, string> = {
    "server-port": String(instance.port),
    "query.port": String(instance.queryPort),
    "rcon.port": String(instance.rconPort),
    "rcon.password": instance.rconPassword,
    "enable-rcon": "true",
    "enable-query": "true",
    motd: instance.motd,
    "max-players": String(instance.maxPlayers),
    difficulty: instance.difficulty,
    gamemode: instance.gamemode,
    pvp: String(instance.pvp),
    "white-list": String(instance.whitelist),
    "online-mode": String(instance.onlineMode),
    "view-distance": String(instance.viewDistance),
    "spawn-protection": map.get("spawn-protection") ?? "16",
    "allow-flight": "true",
    "level-name": map.get("level-name") ?? "world",
    "level-type": map.get("level-type") ?? "DEFAULT",
    "max-tick-time": map.get("max-tick-time") ?? "-1",
    "network-compression-threshold": map.get("network-compression-threshold") ?? "256",
    "prevent-proxy-connections": "false",
    "use-native-transport": "true"
  };

  for (const [key, value] of Object.entries(values)) map.set(key, value);
  writeFileSync(file, stringifyProperties(map));
}

export function readMotd(dir: string) {
  const file = join(dir, "server.properties");
  if (!existsSync(file)) return null;
  return parseProperties(readFileSync(file, "utf8")).get("motd") ?? null;
}
